using UnityEngine;

namespace SeoulFirstWeek.World
{
    /// <summary>Slices of the character fabric texture array (Art/Generated/Characters/Fabrics.png).</summary>
    public enum Fabric
    {
        Skin, Jersey, Knit, Denim, Wool, Twill, Puffer, Leather,
        Sneaker, Canvas, Poplin, Corduroy, Check, Nylon, Satin, Fleece,
    }

    /// <summary>Slices of the hair strand texture array.</summary>
    public enum HairTexture { Straight, Wavy, Curly, Buzz }

    /// <summary>
    /// The shared look of every person: the character material (fabric, normal and face texture arrays on the
    /// <c>SeoulFirstWeek/Character</c> shader), the hair material and the glasses lens. Generated by the editor's
    /// <c>CharacterKit</c> and loaded at runtime from Resources, so people built in play mode (pedestrians,
    /// visitors) look the same as the ones the scene builder saves.
    /// </summary>
    public class HumanStyle : ScriptableObject
    {
        public Material character, hair, lens;

        /// <summary>How many metres one repeat of each fabric slice covers.</summary>
        public static readonly float[] Metres =
        {
            0.09f, 0.08f, 0.12f, 0.14f, 0.2f, 0.07f, 0.36f, 0.12f,
            0.1f, 0.07f, 0.06f, 0.09f, 0.3f, 0.25f, 0.2f, 0.07f,
        };

        /// <summary>Soft fabrics that catch a velvety rim of light (knits, wool, corduroy, fleece).</summary>
        public static readonly bool[] Sheen =
        {
            false, false, true, false, true, false, false, false,
            false, false, false, true, false, false, false, true,
        };

        // UV1.y of every vertex: how the character shader lights it
        public const int TypeCloth = 0, TypeSkin = 1, TypeFace = 2, TypeSheen = 3;

        /// <summary>Faces in the face texture array (4 x 4).</summary>
        public const int FaceCount = 16;

        static HumanStyle current;

        public static HumanStyle Current
        {
            get
            {
                if (!current) current = Resources.Load<HumanStyle>("HumanStyle");
                return current;
            }
        }
    }
}
